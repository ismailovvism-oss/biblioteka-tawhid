#!/usr/bin/env node
'use strict';

/*
 * Аудит библиотеки целиком: `tools/validate.js` проверяет Контракт ВНУТРИ книги,
 * а связность реестра не проверяет никто. Пока книг пять, это видно глазами;
 * на трёхстах гниль копится незаметно — поэтому заводим до наполнения, а не после.
 *
 * Использование: node tools/doctor.js [--строго]
 *   --строго — считать замечания ошибками (код выхода 1). По умолчанию код 1
 *              только на настоящих поломках.
 *
 * Что смотрит: повторы id, пропавшие папки и book.json, обложки, поля под фасеты,
 * ссылки на несуществующие узлы taxonomy, книги на диске мимо реестра,
 * рассогласование реестра и манифеста.
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const КНИГИ = path.join(КОРЕНЬ, 'books');
const строго = process.argv.includes('--строго');

const поломки = [];
const замечания = [];
const ксведению = [];
const беда = (кто, что) => поломки.push(`${кто}: ${что}`);
const косяк = (кто, что) => замечания.push(`${кто}: ${что}`);
const кстати = (кто, что) => ксведению.push(`${кто}: ${что}`);

const читать = п => JSON.parse(fs.readFileSync(п, 'utf8'));
const есть = п => fs.existsSync(п);
const внешняя = base => /^https?:\/\//.test(base || '');

// ── реестр ────────────────────────────────────────────────────────────────
const реестр = читать(path.join(КНИГИ, 'index.json'));
const записи = реестр.books || [];
console.log(`Реестр: ${записи.length} ${записи.length === 1 ? 'книга' : 'книг'}`);

const узлы = new Set();
try {
  for (const c of читать(path.join(КНИГИ, 'taxonomy.json')).categories || []) узлы.add(c.id);
} catch { косяк('taxonomy.json', 'не прочитан — разделы не проверяю'); }

// ── по каждой записи ──────────────────────────────────────────────────────
const виденные = new Set();
const своиПапки = new Set();

for (const з of записи) {
  const кто = `«${(з.title && (з.title.ru || Object.values(з.title)[0])) || з.id}»`;

  if (!з.id) { беда(кто, 'нет id'); continue; }
  if (виденные.has(з.id)) беда(кто, `id «${з.id}» повторяется`);
  виденные.add(з.id);
  if (!з.base) { беда(кто, 'нет base'); continue; }

  // поля, на которых держится полка: без них книга выпадает из фасетов
  for (const [поле, зачем] of [['authors', 'фасет автора'], ['category', 'дерево разделов'],
                               ['langs', 'фасет языка'], ['era', 'фасет эпохи']]) {
    const v = з[поле];
    if (v == null || (Array.isArray(v) && !v.length) || v === '')
      косяк(кто, `нет «${поле}» — не попадёт в ${зачем}`);
  }
  if (з.category && узлы.size && !узлы.has(з.category))
    косяк(кто, `раздел «${з.category}» не описан в taxonomy.json`);

  if (внешняя(з.base)) { косяк(кто, 'книга внешняя — содержимое не проверяю'); continue; }

  const папка = path.join(КОРЕНЬ, з.base);
  своиПапки.add(path.basename(з.base.replace(/\/+$/, '')));
  if (!есть(папка)) { беда(кто, `нет папки ${з.base}`); continue; }

  const манифестП = path.join(папка, 'book.json');
  if (!есть(манифестП)) { беда(кто, 'нет book.json'); continue; }

  let м;
  try { м = читать(манифестП); } catch (e) { беда(кто, `book.json не читается: ${e.message}`); continue; }

  if (м.bookId && м.bookId !== з.id) беда(кто, `bookId в манифесте «${м.bookId}» ≠ id в реестре «${з.id}»`);
  if (з.langs && м.languages) {
    const лишние = з.langs.filter(l => !м.languages.includes(l));
    if (лишние.length) косяк(кто, `в реестре языки ${лишние.join(', ')}, а в манифесте их нет`);
  }
  for (const l of м.rtl || []) if (!(м.languages || []).includes(l))
    косяк(кто, `rtl упоминает язык «${l}», которого нет в languages`);

  if (з.cover && !есть(path.join(КОРЕНЬ, з.cover))) косяк(кто, `обложки нет: ${з.cover}`);

  // Главы. Нет файла у одного языка — это законная односторонняя глава
  // (второй язык ещё не сведён), а не поломка. Поломка — когда главы нет
  // ни на одном языке: тогда она пустая везде.
  const нехватка = {};
  let всего = 0, пустых = 0;
  for (const гл of м.chapters || []) {
    if (!гл.file) continue;                      // запись-группа, читать нечего
    всего++;
    let живых = 0;
    for (const l of м.languages || []) {
      if (есть(path.join(папка, l, гл.file))) живых++;
      else нехватка[l] = (нехватка[l] || 0) + 1;
    }
    if (!живых) { пустых++; беда(кто, `главы «${гл.file}» нет ни на одном языке`); }
  }
  for (const [l, n] of Object.entries(нехватка))
    if (n && n < всего * (м.languages || []).length)
      кстати(кто, `${l}: нет ${n} глав из ${всего} — читаются односторонне`);
}

// ── книги на диске мимо реестра ───────────────────────────────────────────
for (const имя of fs.readdirSync(КНИГИ)) {
  const п = path.join(КНИГИ, имя);
  if (!fs.statSync(п).isDirectory()) continue;
  if (своиПапки.has(имя)) continue;
  if (!есть(path.join(п, 'book.json'))) continue;
  // папки с подчёркиванием — эталонные для разработки, их в реестре может и не быть
  const скажем = имя.startsWith('_') ? кстати : косяк;
  скажем(`books/${имя}`, 'книга есть на диске, но не внесена в index.json');
}

// ── итог ──────────────────────────────────────────────────────────────────
const печать = (заголовок, список) => {
  if (!список.length) return;
  console.log(`\n${заголовок}`);
  for (const с of список) console.log('  • ' + с);
};
печать('Поломки:', поломки);
печать('Замечания:', замечания);
печать('К сведению:', ксведению);

if (!поломки.length && !замечания.length) console.log('\nБиблиотека в порядке ✓');
else console.log(`\nПоломок: ${поломки.length}, замечаний: ${замечания.length}`);

process.exit(поломки.length || (строго && замечания.length) ? 1 : 0);
